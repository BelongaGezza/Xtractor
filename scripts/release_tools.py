#!/usr/bin/env python3
"""Helpers for build_binary.sh: write the embedded-tool manifest, build the release tarball.

release_tools.py manifest STAGE_DIR APP_VERSION FFMPEG JS_EXE JS_YTDLP_NAME
release_tools.py tarball  OUT_TARBALL BINARY LICENSE NOTICES
"""

from __future__ import annotations

import gzip
import hashlib
import io
import json
import os
import shutil
import sys
import tarfile
from pathlib import Path


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_manifest(stage: Path, app_version: str, ffmpeg: Path, js_exe: Path, js_name: str) -> Path:
    """Copy the tools into ``stage/xtractor_bundle`` and write ``manifest.json`` there."""
    out = stage / "xtractor_bundle"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    assets: dict[str, dict[str, object]] = {}
    for key, src in (("ffmpeg", ffmpeg), ("js", js_exe)):
        dst = out / src.name
        shutil.copy2(src, dst)
        dst.chmod(0o755)
        assets[src.name if key == "js" else key] = {
            "name": src.name,
            "sha256": sha256(dst),
            "size": dst.stat().st_size,
        }
    manifest = {
        "app_version": app_version,
        "assets": assets,
        "js": {"name": js_name, "asset": js_exe.name},
    }
    text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    path = out / "manifest.json"
    path.write_text(text)
    write_blob_module(stage / "blob" / "xtractor_blob.py", text, out, assets)
    return path


def write_blob_module(
    dest: Path, manifest_text: str, files_dir: Path, assets: dict[str, dict[str, object]]
) -> None:
    """Generate ``xtractor_blob.py``: the tools as bytes constants, stored in the PYZ.

    Python modules inside a PyInstaller archive are not unpacked at start-up, whereas
    data files and binaries are unpacked to a temp dir on EVERY launch of a --onefile.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("w") as fh:
        fh.write('"""Generated by scripts/release_tools.py. Do not edit."""\n\n')
        fh.write(f"MANIFEST = {manifest_text!r}\n")
        fh.write("FILES = {\n")
        for meta in assets.values():
            name = str(meta["name"])
            fh.write(f"    {name!r}: {(files_dir / name).read_bytes()!r},\n")
        fh.write("}\n")


def make_tarball(out: Path, binary: Path, license_file: Path, notices: Path) -> None:
    """Reproducible flat ``.tar.gz``: Xtractor, LICENSE, THIRD_PARTY_NOTICES."""
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as tf:
        for src, arcname, mode in (
            (binary, "Xtractor", 0o755),
            (license_file, "LICENSE", 0o644),
            (notices, "THIRD_PARTY_NOTICES", 0o644),
        ):
            info = tarfile.TarInfo(arcname)
            info.size = src.stat().st_size
            info.mode = mode
            info.mtime = epoch
            with src.open("rb") as fh:
                tf.addfile(info, fh)
    with (
        out.open("wb") as raw,
        gzip.GzipFile(fileobj=raw, mode="wb", mtime=epoch, filename="") as gz,
    ):
        gz.write(buf.getvalue())


def main(argv: list[str]) -> int:
    if len(argv) == 7 and argv[1] == "manifest":
        write_manifest(Path(argv[2]), argv[3], Path(argv[4]), Path(argv[5]), argv[6])
        return 0
    if len(argv) == 6 and argv[1] == "tarball":
        make_tarball(Path(argv[2]), Path(argv[3]), Path(argv[4]), Path(argv[5]))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
